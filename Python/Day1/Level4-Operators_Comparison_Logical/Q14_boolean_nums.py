# Ask user to enter two numbers and check greater than, less than and equal of first number with second number
num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))

print(f"First number is greater than second: {num1 > num2}")
print(f"First number is less than second: {num1 < num2}")
print(f"First number is equal to second: {num1 == num2}")